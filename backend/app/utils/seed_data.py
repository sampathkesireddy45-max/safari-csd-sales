def seed_database_if_empty(db):
    """
    Automatically verifies and bootstraps essential master data on cloud deployment startup.
    Ensures that Render/PostgreSQL/ephemeral instances always have the complete
    8 store locations, registered canteen staff, and all 100 official Safari SKUs.
    """
    from .. import models

    try:
        # 1. Seed Locations
        loc_count = db.query(models.Location).count()
        if loc_count == 0:
            print("==> Auto-seeding 8 Store Canteen Locations...")
            for l_data in LOCATIONS_DATA:
                loc = models.Location(
                    id=l_data.get("id"),
                    location_id=l_data.get("location_id"),
                    name=l_data.get("name"),
                    address=l_data.get("address"),
                    latitude=l_data.get("latitude"),
                    longitude=l_data.get("longitude"),
                    is_active=l_data.get("is_active", True)
                )
                db.add(loc)
            db.commit()
            print("==> 8 Store Canteen Locations successfully seeded.")

        # 2. Seed Employees
        emp_count = db.query(models.Employee).count()
        if emp_count <= 1:
            print("==> Auto-seeding Canteen Employees...")
            for e_data in EMPLOYEES_DATA:
                existing = db.query(models.Employee).filter(models.Employee.employee_id == e_data["employee_id"]).first()
                if not existing:
                    emp = models.Employee(
                        id=e_data.get("id"),
                        employee_id=e_data["employee_id"],
                        firebase_uid=e_data.get("firebase_uid"),
                        name=e_data["name"],
                        email=e_data["email"],
                        phone=e_data.get("phone"),
                        role=e_data.get("role", "employee"),
                        status=e_data.get("status", "active"),
                        assigned_location_id=e_data.get("assigned_location_id"),
                        hashed_password=e_data["hashed_password"]
                    )
                    db.add(emp)
            db.commit()
            print("==> Employees successfully synced & seeded.")

        # 3. Seed Products (100 Official Safari Catalog Items)
        prod_count = db.query(models.Product).count()
        if prod_count == 0:
            print("==> Auto-seeding 100 Official Safari SKUs...")
            for p_data in PRODUCTS_DATA:
                prod = models.Product(
                    id=p_data.get("id"),
                    product_id=p_data.get("product_id") or p_data.get("index_no"),
                    name=p_data["name"],
                    description=p_data.get("description"),
                    is_active=True,
                    index_no=p_data.get("index_no"),
                    rate_per_pc=p_data.get("rate_per_pc"),
                    selling_rate=p_data.get("selling_rate"),
                    brand=p_data.get("brand"),
                    colour=p_data.get("colour"),
                    category=p_data.get("category"),
                    sub_category=p_data.get("sub_category"),
                    case_pack=p_data.get("case_pack", 1)
                )
                db.add(prod)
            db.commit()
            print("==> 100 Official Safari SKUs successfully seeded.")

        # 4. Initialize Baseline Inventories across all stores
        inv_count = db.query(models.Inventory).count()
        if inv_count == 0:
            print("==> Auto-initializing baseline store inventories...")
            locations = db.query(models.Location).all()
            products = db.query(models.Product).all()
            for loc in locations:
                for prod in products:
                    inv = models.Inventory(
                        location_id=loc.id,
                        product_id=prod.id,
                        quantity=0
                    )
                    db.add(inv)
            db.commit()
            print("==> Baseline store inventories successfully initialized.")

    except Exception as e:
        print(f"Notice during seed_database_if_empty: {e}")
        db.rollback()
